#!/usr/bin/env python3
"""Emit the run_id -> root map for `casf-extended-analysis --generation-root-overrides`.

The bundled run roots under `data/results/runs/` carry only
`analysis/tables/geometric_per_ligand_long.csv`, which is all the dashboard build
needs. K-efficiency and the energy windows additionally read `generation/` and
`geometric_energy_values.csv`, which exist only under the full Weka run roots.

This probes every root in the Weka sources config and emits those whose
`generation/` tree is readable, letting the extended analysis keep the dashboard's
provenance while reading per-conformer data from a fuller copy of each run.
Unreadable roots are reported and left out.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
CONFIG_DIR = REPO / "src" / "casf_benchmark" / "config"
HEADER = """# GENERATED by scripts/build_generation_root_overrides.py -- do not edit by hand.
# run_id -> root holding the readable generation/ tree, for per-conformer analyses only.
"""


def probe(root: str) -> tuple[bool, str]:
    generation = os.path.join(root, "generation")
    if not os.access(generation, os.R_OK | os.X_OK):
        return False, "generation/ unreadable"
    energies = os.path.join(root, "analysis", "tables", "geometric_energy_values.csv")
    if not os.access(energies, os.R_OK):
        return True, "SDFs readable, geometric_energy_values.csv unreadable (energy windows will skip)"
    return True, "full"


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--weka-config", type=Path, default=CONFIG_DIR / "casf_analysis_sources.weka.yaml")
    parser.add_argument("--output", type=Path, default=CONFIG_DIR / "casf_generation_root_overrides.yaml")
    args = parser.parse_args()

    weka = yaml.safe_load(args.weka_config.read_text())
    overrides: dict[str, str] = {}
    partial: list[str] = []
    blocked: list[str] = []
    for key in ("sources", "reference_sources"):
        for entry in weka.get(key) or []:
            usable, note = probe(entry["root"])
            if not usable:
                blocked.append(f"{entry['run_id']}: {entry['root']} ({note})")
                continue
            overrides[entry["run_id"]] = entry["root"]
            if note != "full":
                partial.append(f"{entry['run_id']}: {note}")

    with args.output.open("w") as handle:
        handle.write(HEADER)
        yaml.safe_dump({"generation_roots": overrides}, handle, sort_keys=True, width=200)

    print(f"wrote {args.output} ({len(overrides)} usable roots)")
    for item in partial:
        print(f"  PARTIAL  {item}")
    for item in blocked:
        print(f"  BLOCKED  {item}")


if __name__ == "__main__":
    main()
